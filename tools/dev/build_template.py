#!/usr/bin/env python3
"""Build switch/lab.template.yaml from switch/lab.base.yaml and agents/*.md."""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
# Agents already on the dev server, which only the owner can delete. Used for switch/.partial-run.yaml only.
EXISTING = {"bandit", "patch", "reviewer-2"}


class NoAliases(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def text_block(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|" if "\n" in data else None)


NoAliases.add_representer(str, text_block)

doc = yaml.safe_load((ROOT / "switch/lab.base.yaml").read_text())
for agent in doc["agents"]:
    agent["instructions"] = (ROOT / f"agents/{agent['name']}.md").read_text().strip() + "\n"
partial = [a for a in doc["agents"] if a["name"] not in EXISTING]
out_partial = dict(doc, agents=partial)
(ROOT / "switch/.partial-run.yaml").write_text(yaml.dump(out_partial, Dumper=NoAliases, sort_keys=False, width=100, allow_unicode=True))
out = "# Generated by `just template`. Edit lab.base.yaml and agents/*.md instead.\n"
out += yaml.dump(doc, Dumper=NoAliases, sort_keys=False, width=100, allow_unicode=True)
(ROOT / "switch/lab.template.yaml").write_text(out)
